import assert from 'node:assert/strict';
import http from 'node:http';
import { readFileSync } from 'node:fs';
import path from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve('dist/static-pwa');
const base = process.env.PWA_BASE || '/hadith-alqulub/';
let release = 'old', failDownload = false;
const server = http.createServer((req, res) => {
  const pathname = new URL(req.url, 'http://localhost').pathname;
  if (!pathname.startsWith(base)) return res.writeHead(404).end();
  const relative = decodeURIComponent(pathname.slice(base.length)) || 'index.html';
  const file = path.resolve(root, relative);
  if (!file.startsWith(root + path.sep)) return res.writeHead(403).end();
  if (failDownload && relative.endsWith('.woff2')) return res.writeHead(503).end();
  try {
    let body = readFileSync(file);
    if (relative === 'sw.js') body = body.toString().replace(/const REVISION = "[^"]+";/, `const REVISION = "${release}";`);
    res.setHeader('Cache-Control', 'no-store');
    res.setHeader('Content-Type', ({ '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml' })[path.extname(file)] || 'application/octet-stream');
    res.end(body);
  } catch { res.writeHead(404).end(); }
});
await new Promise(r => server.listen(0, '127.0.0.1', r));
const url = `http://127.0.0.1:${server.address().port}${base}`;
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: JSON.parse(process.env.CHROMIUM_ARGS || '[]'), headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(url);
  await page.getByLabel('تخطي الجولة التعريفية').click();
  await page.getByLabel('اسم اللاعب الأول').fill('علي');
  await page.getByLabel('اسم اللاعب الثاني').fill('فاطمة');
  await page.getByRole('button', { name: 'بدء الجلسة', exact: false }).click();
  await page.getByRole('button', { name: /علي/ }).click();
  await page.locator('.question-card').first().click();
  const prompt = await page.locator('.legacy-question-card__copy').innerText();
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
  await page.reload();
  await page.getByRole('button', { name: 'استئناف جلسة سابقة' }).waitFor();
  await page.getByRole('button', { name: 'الإعدادات', exact: true }).click();
  await page.getByText('old', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'البحث عن تحديث', exact: true }).click();
  await page.getByText('نسختك محدّثة.', { exact: true }).waitFor();
  await context.setOffline(true);
  await page.getByRole('button', { name: 'البحث عن تحديث', exact: true }).click();
  await page.getByText(/اتصل بالإنترنت للبحث/).waitFor();
  await context.setOffline(false);
  release = 'broken'; failDownload = true;
  await page.getByRole('button', { name: 'البحث عن تحديث', exact: true }).click();
  await page.getByText(/تعذر تنزيل التحديث كاملًا/).waitFor();
  assert(await page.evaluate(async () => (await caches.keys()).some(k => k.endsWith(':old'))));
  await context.setOffline(true); await page.reload();
  await page.getByRole('button', { name: 'استئناف جلسة سابقة' }).click();
  assert.equal(await page.locator('.legacy-question-card__copy').innerText(), prompt);
  await page.reload();
  await page.getByRole('button', { name: 'استئناف جلسة سابقة' }).waitFor();
  await page.getByRole('button', { name: 'الإعدادات', exact: true }).click();
  release = 'new'; failDownload = false;
  await context.setOffline(false);
  await page.getByRole('button', { name: 'البحث عن تحديث', exact: true }).click();
  await page.getByRole('button', { name: 'تثبيت التحديث وإعادة فتح اللعبة', exact: true }).waitFor();
  const saved = await page.evaluate(() => localStorage.getItem('hadith-alqulub-platform-session-v1'));
  await page.evaluate(() => localStorage.setItem('update-test-sentinel', 'keep'));
  await context.setOffline(true);
  await Promise.all([page.waitForEvent('framenavigated'), page.getByRole('button', { name: 'تثبيت التحديث وإعادة فتح اللعبة', exact: true }).click()]);
  await page.getByRole('button', { name: 'استئناف جلسة سابقة' }).waitFor();
  assert.equal(await page.evaluate(() => localStorage.getItem('update-test-sentinel')), 'keep');
  assert.equal(await page.evaluate(() => localStorage.getItem('hadith-alqulub-platform-session-v1')), saved);
  await page.getByRole('button', { name: 'استئناف جلسة سابقة' }).click();
  assert.equal(await page.locator('.legacy-question-card__copy').innerText(), prompt);
  await page.reload();
  await page.getByRole('button', { name: 'استئناف جلسة سابقة' }).waitFor();
  await page.getByRole('button', { name: 'الإعدادات', exact: true }).click();
  await page.getByText('new', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  await context.close();
  console.log('PASS: manual check, no update, offline check, failed precache preserves usable old version, retry, install while offline, session + unrelated storage preserved, new active revision.');
} finally { await browser.close(); await new Promise(r => server.close(r)); }
